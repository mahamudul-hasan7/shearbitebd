import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { apiError, ApiError, object, requireAuth, textField } from "@/lib/api";

export async function GET() {
  try {
    const { user } = await requireAuth();
    const notifications = await prisma.notification.findMany({ where: { userId: user.id }, orderBy: { createdAt: "desc" }, take: 100 });
    return NextResponse.json({ success: true, count: notifications.length, unreadCount: notifications.filter((n) => !n.readAt).length, notifications: notifications.map((n) => ({ ...n, read: Boolean(n.readAt) })) });
  } catch (error) { return apiError(error); }
}

export async function POST() {
  return NextResponse.json({ error: "Notifications are generated by server operations." }, { status: 403 });
}

export async function PATCH(request: Request) {
  try {
    const { user } = await requireAuth();
    const body = object(await request.json());
    const id = textField(body.id, "id", 200);
    const result = await prisma.notification.updateMany({ where: { id, userId: user.id }, data: { readAt: body.read === false ? null : new Date() } });
    if (!result.count) throw new ApiError(404, "Notification not found.");
    const notification = await prisma.notification.findUniqueOrThrow({ where: { id } });
    return NextResponse.json({ success: true, notification: { ...notification, read: Boolean(notification.readAt) } });
  } catch (error) { return apiError(error); }
}
